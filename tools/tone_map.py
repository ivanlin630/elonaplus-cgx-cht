"""Chinese values for the Japanese speech-tone tables in text.hsp.

Ending functions (appended to a sentence) mostly vanish in Chinese; phrase
functions (greetings, thanks, pronouns...) are translated by hand keeping the
character's register. tone_zh(func, jp) returns the Chinese text ('' = drop).
"""
import re

CAT = ('にゃ', 'ニャ', 'みゃ', 'ミャ', 'にぁ', 'ニァ', 'みぁ', 'ミァ', 'にゅ', 'みぅ', 'みゅ')
QUESTION = {'_ka', '_kana', '_noka'}
ENDING = {'_da', '_nda', '_noka', '_ka', '_kana', '_ru', '_ga', '_dana', '_daro',
          '_yo', '_aru', '_u', '_na', '_ta', '_siro', '_kure'}


def ending(func, jp):
    tail = '……' if jp.endswith('…') else ''
    core = jp.rstrip('…')
    if any(c in jp for c in CAT):
        return '喵' + tail
    if func in QUESTION:
        return ('嗎' if core else '') + tail
    if func == '_daro':
        return ('吧' if core else '') + tail
    if func == '_ga':
        return tail
    if core.endswith(('ね', 'な', 'なぁ', 'のう', 'わね')):
        return '呢' + tail
    if core.endswith(('よ', 'わよ', 'ッスよ', 'ますよ', 'ですよ')):
        return '喔' + tail
    if core.endswith(('ぜ', 'ぞ', 'ぞよ')):
        return '啦' + tail
    return tail


