def _ok(s):
    try:
        s.encode('cp932'); return True
    except UnicodeEncodeError:
        return False


import re as _re
# OpenCC s2tw turns 只 (only) into the measure word 隻 everywhere; undo it before verbs
_ZHI = _re.compile('隻(?=能|要|有|靠|看|給|會|好|剩|見|不過|得|需)')


# one spelling per place / name (machine translation varied), and words whose
# character substitution would read wrong (酒吧 -> 酒罷)
NORMALIZE = [
    (_re.compile('[維韋威]爾尼[斯思絲]'), '維爾尼斯'),
    (_re.compile('巴羅米亞|巴爾米亞'), '帕爾米亞'),
    (_re.compile('諾伊艾|諾伊爾'), '諾耶爾'),
    (_re.compile('約溫'), '約恩'),
    (_re.compile('盧米[艾埃]斯特|魯米埃斯特'), '魯米艾斯特'),
    (_re.compile('奈菲亞'), '涅菲亞'),
    (_re.compile('酒吧'), '酒場'),
    (_re.compile('吧台|吧檯'), '櫃台'),
]


def sjis_safe(text, lost=None):
    global _jp, _ts
    text = _ZHI.sub('只', text)
    for rx, rep in NORMALIZE:
        text = rx.sub(rep, text)
    if _jp is None:
        import opencc
        _jp = opencc.OpenCC('t2jp'); _ts = opencc.OpenCC('t2s')
    out = []
    for ch in text:
        if ord(ch) < 128 or _ok(ch):
            out.append(ch); continue
        if M.get(ch) == '':
            if lost is not None:
                lost[ch] = ''
            continue                      # mapped to nothing (interjection, zero-width)
        alt = None
        for cand in M.get(ch, ''):
            if _ok(cand):
                alt = cand; break
        if alt is None:
            for cand in (_jp.convert(ch), _jp.convert(_ts.convert(ch)), unicodedata.normalize('NFKC', ch)):
                if cand != ch and cand and _ok(cand):
                    alt = cand; break
        if alt is None:
            alt = '?'
        if lost is not None:
            lost[ch] = alt
        out.append(alt)
    return ''.join(out)
